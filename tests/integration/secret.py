"""Секреты тестов: значение — как у строки или байтов, repr — без значения (ревью А7 I1, итоговое ревью Д6а P7).

pytest печатает аргументы кадров трассировки (первого и последнего, при --tb=long — всех) и локальные переменные при
--showlocals через repr. Склейка (secret + "\\n", f"…{secret}") даёт обычную str — оборачивать после неё. Модуль
отдельный: его берут и conftest, и gwclient (conftest сам импортирует gwclient — круг импорта).
"""


class Secret(str):
    """Пароль, cookie, токен: в трассировке — «<скрыт>»."""

    def __repr__(self) -> str:
        return "<скрыт>"


class SecretBytes(bytes):
    """Тело запроса с паролем: в трассировке — только длина."""

    def __repr__(self) -> str:
        return f"<скрыто: {len(self)} байт>"
