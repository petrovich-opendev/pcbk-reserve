"""Секреты стенда отбора (Д8-R76): значение — как у строки или байтов, repr — без значения.

Своя копия tests/integration/secret.py: стенд отбора — отдельный пакет только на stdlib (интеграция импортирует
его, а не наоборот). pytest печатает аргументы кадров трассировки и локальные переменные через repr. Склейка
(secret + "\\n", f"…{secret}") даёт обычную str — оборачивать после неё.
"""


class Secret(str):
    """Пароль, cookie, токен: в трассировке — «<скрыт>»."""

    def __repr__(self) -> str:
        return "<скрыт>"


class SecretBytes(bytes):
    """Тело запроса с паролем: в трассировке — только длина."""

    def __repr__(self) -> str:
        return f"<скрыто: {len(self)} байт>"
