def _a1(edit_text=None, save_tags=None):
    r = honest_a_record("A1")
    for t in r.turns:
        if edit_text:
            t.assistant = [edit_text(x) for x in t.assistant]
        for c in t.tools:
            if save_tags is not None and c.tool == "pcbk_save_agent":
                c.input["tags"] = list(save_tags)
    return check_run(r, card("A1"))


