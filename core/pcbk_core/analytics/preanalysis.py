# --- точный разбор написанных единиц (не угадывание отсутствующей единицы, только чтение написанной) ---

_UNIT_TOKENS: tuple[str, ...] = (
    "%", "м³/ч", "м3/ч", "т/ч", "т/м³", "т/м3", "г/м²", "г/м2", "кн/м", "н/м", "кпа", "мбар", "бар",
    "л/мин", "м/мин", "кг/ч", " мм", "куб/ч", "кубов в час", "кубометров в час",
)
# Правка Task 3 (Д17, план §Task 3/Этап 3): словесные формы объёмного расхода («кубов в час»/«кубометров в
# час»/«куб/ч») — та же единица, что «м3/ч» (`calculations._FLOW_RE` признаёт их тем же физическим входом), не
# три разных значения `unit_hint` — отсюда канонизация ниже вместо буквального `token.strip()` для этих форм.
_VOLUME_FLOW_WORD_TOKENS: frozenset[str] = frozenset({"куб/ч", "кубов в час", "кубометров в час"})
_VOLUME_FLOW_CANONICAL_UNIT = "м3/ч"


def _find_unit_hint(text: str) -> str | None:
    lowered = text.lower()
    for token in _UNIT_TOKENS:
        if token in lowered:
            return _VOLUME_FLOW_CANONICAL_UNIT if token in _VOLUME_FLOW_WORD_TOKENS else token.strip()
    return None


# --- служебные слова русского языка, исключённые из попыток разрешения терминов (см. докстринг модуля) ---

_STOPWORDS: frozenset[str] = frozenset({
    "что", "как", "это", "или", "для", "при", "если", "чтобы", "когда", "где", "кто", "почему", "так",
    "уже", "еще", "ещё", "только", "либо", "да", "нет", "же", "ли", "бы", "не", "ни", "на", "по", "из",
    "от", "до", "за", "под", "над", "без", "через", "между", "среди", "со", "об", "обо", "во", "и", "а",
    "но", "то", "там", "тут", "вот", "все", "весь", "всё", "его", "её", "их", "мне", "нам", "вам", "им",
    "быть", "есть", "был", "была", "было", "были", "можно", "нужно", "надо", "сейчас", "сегодня",
})

_TOKEN_RE = re.compile(r"[A-Za-zА-Яа-яЁё]+")
_DIGIT_TOKEN_RE = re.compile(r"\d{1,2}")

# Правка контроллера, раунд 2, п.2: «масса 1 м²»/«масса квадратного метра»/«масса м2»/«граммаж» — контекстно
# ОДНОЗНАЧНЫЙ термин корпуса (id "basis-weight", preferred_ru «Масса квадратного метра», aliases «граммаж»/
# «масса 1 м²» — проверено на настоящем корпусе `KDM1_PACKAGE_DIR`). Корпус помечает этот термин `ambiguous:
# true`, но сама его карточка объясняет, ЧТО там неоднозначно: база измерения (сухое/влажное вещество), не
# то, какое слово «масса» из нескольких корпусных терминов имелось в виду — это другая неоднозначность
# (`"basis"`, не `"quantity"`). Без этого исключения одинокое слово «масса» из такой фразы резолвится И как
# «basis-weight» (граммаж), И как «stock»/«stock-preparation»/«consistency» (другие термины корпуса, чьи
# preferred_ru/aliases тоже содержат слово «масса» — «Масса», «Подготовка массы», «сухость массы») —
# технолог, буквально написавший квалификатор «1 м²»/«квадратного метра»/«граммаж», уже снял неоднозначность
# текстом (мастер-промпт §4: контекст читается, не угадывается) — слово «масса» внутри такой фразы (и сама
# фраза «граммаж») из разбора по отдельным словам ниже исключается, второй раз как многозначное не резолвится.
_BASIS_WEIGHT_PHRASE_RE = re.compile(
    r"масса\s+(?:1\s*)?м[²2]\b|масса\s+квадратного\s+метра|граммаж\w*", re.IGNORECASE)


def _basis_weight_phrase_spans(text: str) -> list[tuple[int, int]]:
    """Диапазоны `_BASIS_WEIGHT_PHRASE_RE` в тексте — общие и для `_content_tokens` (слово «масса»/«граммаж»
    не резолвится по отдельности как многозначное), и для `_digit_node_process_ids` (цифра «1» из «1 м²»/
    «м2» — часть обозначения единицы площади, не номер узла/бассейна КДМ-1, см. докстринг той функции)."""
    return [m.span() for m in _BASIS_WEIGHT_PHRASE_RE.finditer(text)]


def _span_within(start: int, end: int, spans: list[tuple[int, int]]) -> bool:
    return any(span_start <= start and end <= span_end for span_start, span_end in spans)


def _content_tokens_with_positions(text: str, *, extra_excluded_spans: tuple[tuple[int, int], ...] = ()
                                   ) -> list[tuple[str, int, int]]:
    """Как `_content_tokens` ниже, но с положением каждого слова в тексте — правка Task 3, раунд 1 (Д17):
    `_resolve_question_terms` должен расставить пословные и фразовые (узел/термин) результаты в ПОРЯДКЕ
    исходного текста вопроса, а не в порядке, в котором их нашли разные механизмы."""
    seen: set[str] = set()
    result: list[tuple[str, int, int]] = []
    excluded_spans = _basis_weight_phrase_spans(text) + list(extra_excluded_spans)
    for match in _TOKEN_RE.finditer(text):
        word = match.group(0)
        if len(word) < 2:
            continue
        start, end = match.span()
        if _span_within(start, end, excluded_spans):
            continue
        key = word.lower()
        if key in _STOPWORDS or key in seen:
            continue
        seen.add(key)
        result.append((word, start, end))
    return result


def _content_tokens(text: str, *, extra_excluded_spans: tuple[tuple[int, int], ...] = ()) -> list[str]:
    """`extra_excluded_spans` — правка Task 3 (Д17, план §Task 3/Этап 3): дополнительные диапазоны вне
    `_basis_weight_phrase_spans`, чьи слова не нужно резолвить по отдельности — на практике это слова фразы
    узла/термина (`_process_phrase_matches`/`_term_phrase_matches`), вызывается только из `_resolve_question_
    terms`; старые вызывающие (`_has_substantive_remainder_after_other_machine` и сам этот модуль без
    аргумента) не передают его и получают прежнее поведение в точности."""
    return [word for word, _start, _end in _content_tokens_with_positions(
        text, extra_excluded_spans=extra_excluded_spans)]


def original_and_normalized(request: "AnalysisRequest") -> NormalizedQuestion:
    """Пункт 2 мастер-промпта §7: сохранение оригинала вопроса отдельно от нормализации, до разрешения терминов
    и до любого обращения к LLM. `unit_hint`/`process_hint` — явный `context`, иначе буквальное чтение текста
    (см. докстринг модуля/`_find_unit_hint`); при отсутствии и там, и там — `None`, единица не угадывается."""
    original = request.question
    normalized = terms.normalize_ru(original)
    unit_hint = None
    process_hint = None
    if request.context is not None:
        unit_hint = request.context.unit_hint
        process_hint = request.context.process_id
    if unit_hint is None:
        unit_hint = _find_unit_hint(original)
    return NormalizedQuestion(original=original, normalized=normalized, unit_hint=unit_hint,
                              process_hint=process_hint)


