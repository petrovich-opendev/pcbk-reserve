_IMPERATIVE_PLURAL_RE = re.compile(r"\w{2,}(?:ите|йте|ьте)$")
_INFINITIVE_ENDING_RE = re.compile(r"\w{3,}(?:ить|ать|ять|еть|уть|ыть|оть|чь)$")
_PAST_PLURAL_RE = re.compile(r"\w+[аяиыеуо]ли$")
_OJ_IMPERATIVE_RE = re.compile(r"^(?:(?:от|за|при|пере|на|рас|под|по)?крой|(?:на|пере|по|в|до|под)?строй|"
                               r"(?:про|от|вы|по|с|у|за|под|об)?мой)$")
_SECOND_PERSON_RE = re.compile(r"\b\w{3,}(?:ешь|ёшь|ишь)\b", re.IGNORECASE)


def _imperative_like(word: str) -> bool:
    """Окончание повелительной формы или инфинитива — с исключениями для существительных, прилагательных и
    прошедшего времени на те же буквы (см. `_NOT_IMPERATIVE`, падежные окончания ниже)."""
    w = word.lower()
    if w in _NOT_IMPERATIVE or len(w) < 3 or _PAST_PLURAL_RE.match(w):
        return False                            # «открыли», «включили», «подкрутили» — сводка, не просьба
    if _IMPERATIVE_PLURAL_RE.match(w) or _INFINITIVE_ENDING_RE.match(w):
        return True
    if w.endswith("и"):
        if w.endswith("еки"):
            return True                        # отсеки, пресеки, засеки — не «уставки», «сетки», «задвижки»
        if w.endswith(("ии", "ки", "ги", "хи", "чи", "ци", "щи", "ами", "ями", "ыми")):
            return False
        if w.endswith("ими") and len(w) >= 6:
            return False                       # «другими», «своими»; но «сними», «прими» — повелительные
        if w.endswith("сти"):
            return w.endswith(("усти", "исти"))  # пусти, запусти, почисти — да; части/скорости/вести — нет
        return True
    if w.endswith("й"):
        if w.endswith(("уй", "лей")):
            return True                        # продуй, отрегулируй; долей, налей
        if w.endswith(("ай", "яй")):
            return True                        # дай, подай, поменяй, включай (исключения — `_NOT_IMPERATIVE`)
        return bool(_OJ_IMPERATIVE_RE.match(w))  # открой, настрой, промой — не «второй», «быстрой», «системой»
    if w.endswith("ь"):
        if w.endswith(("лась", "лось", "лись", "ется", "ится")):
            return False                       # «снизилась», «открылось» — прошедшее/настоящее, не просьба
        return w.endswith(("вь", "сь", "жь", "ерь", "нь"))  # стравь, сбрось, отрежь, проверь, скинь
    return False


_SENTENCE_SPLIT_RE = re.compile(r"[^.!?;\n]+[.!?;]*")


def _sentences(text: str) -> list[str]:
    """Предложения вместе с завершающим знаком — вопросительный знак нужен `_generic_control`."""
    return [s for s in _SENTENCE_SPLIT_RE.findall(text) if s.strip()]


def _sentence_spans(text: str) -> list[tuple[int, int]]:
    """Диапазоны предложений в исходном тексте (та же разбивка, что `_sentences`, тем же регэкспом — только с
    положением, не текстом) — правка ревью Task 3, раунд 3 (Critical C1): `_process_phrase_matches`/`_term_
    phrase_matches` не должны склеивать слова двух разных предложений в одну фразу узла/термина, та же
    дисциплина, что уже есть у `_generic_control` для команд (L438 — «рамка в соседнем предложении не
    снимает»)."""
    return [m.span() for m in _SENTENCE_SPLIT_RE.finditer(text) if m.group(0).strip()]


def _generic_control(sentence: str) -> bool:
    """Общий слой (правки, раунды 3–4): предмет процесса + нет справочной рамки + признак обращения к
    исполнителю. Проверяется по предложению — рамка в соседнем предложении не снимает."""
    if _INFO_FRAME_RE.search(sentence):
        return False
    if sentence.rstrip().endswith("?") and _QUESTION_ONLY_FRAME_RE.search(sentence):
        return False                           # «как работает…?», «если остановить…, будет…?»
    if re.match(r"\s*как\w{0,3}\b", sentence, re.IGNORECASE):
        return False                           # «Как устроена задвижка» без знака вопроса
    has_object = bool(_OPERABLE_OBJECT_RE.search(sentence))
    has_action_noun = bool(_ACTION_NOUN_RE.search(sentence))
    has_process_noun = has_object or bool(_PROCESS_NOUN_RE.search(sentence))
    if not (has_process_noun or has_action_noun):
        return False
    words = [w.lower() for w in _WORD_RE.findall(sentence)]
    if any(w in ("пусть", "пускай") for w in words) and has_process_noun:
        return True
    if _REQUEST_FRAME_RE.search(sentence) and has_process_noun:
        return True                            # «хочу, чтобы вы подняли…», «можно я закрою…», «должен быть закрыт»
    if _YOU_PLURAL_RE.search(sentence) and has_process_noun and not sentence.rstrip().endswith("?"):
        return True                            # «было бы неплохо, если вы прикроете задвижку»
    if _SECOND_PERSON_RE.search(sentence) and has_object:
        return True                            # «откроешь задвижку?»
    if has_action_noun and (has_process_noun or _ACTION_NOUN_RE.search(sentence).group(0).lower().startswith(
            "команд")) and (_URGENCY_RE.search(sentence) or "команд" in sentence.lower()):
        return True                            # «сброс аварии на пульте, срочно», «команда: останов насоса»
    return has_process_noun and any(_imperative_like(w) for w in words)


def _is_control_command(original: str) -> bool:
    """Управление = императив (всегда, рамка не снимает) ИЛИ (инфинитив действия/вопрос о процедуре/«давай» +
    1 л. мн.ч./«переведи-выведи» рядом со словом режима) БЕЗ теоретической рамки в том же предложении (п.3
    задания: «рамка снимает признак, если в предложении нет повелительной формы»). «Переведи/выведи» рядом со
    словом режима — отдельная, многозначная форма (см. докстринг `_MODE_SWITCH_VERB_RE`: единицы измерения —
    не режим работы, «переведи 80 кН/м в бары» не управление). Затем общий слой `_generic_control` по каждому
    предложению (правки, раунды 3–4) — для незнакомых глаголов, порядка «объект — глагол» и форм без глагола."""
    if (_IMPERATIVE_RE.search(original) or _DAVAY_FIRST_PERSON_RE.search(original)
            or (_MODE_SWITCH_VERB_RE.search(original) and _MODE_CONTEXT_RE.search(original))):
        return True
    if (_INFINITIVE_RE.search(original) or _CONTROL_QUESTION_RE.search(original)) \
            and not _THEORY_FRAME_RE.search(original):
        return True
    return any(_generic_control(sentence) for sentence in _sentences(original))


# Правка, раунд 1: чужая машина — регулярное выражение «код машины + номер», не фиксированный список. Код —
# 1–3 буквы + «дм» («кдм», «бдм», возможные другие «…ДМ»-машины линии) ИЛИ буквальное «пм»; разделитель —
# дефис/пробел/ничего, любой регистр («КДМ 2», «БДМ2», «КДМ-2», «кдм2», «ПМ-3» — все формы). Единственная
# разрешённая пара — «кдм»+«1» в любом написании («КДМ1», «КДМ 1», «КДМ-1»); любая другая пара — чужая машина.
# Код специально НЕ произвольные 2–4 буквы подряд (ловили бы обычные русские слова перед числом — «узел 1»,
# «бассейн №8» — как чужую машину): «…дм»/«пм» — спецификация пакета (-делательная машина/прессовая машина),
# обычные слова корпуса на это окончание не оканчиваются.
_MACHINE_CODE_RE = re.compile(r"\b([а-яa-zё]{1,3}дм|пм)[\s-]?(\d{1,2})\b", re.IGNORECASE)
_IN_SCOPE_MACHINE_CODE = "кдм"
_IN_SCOPE_MACHINE_NUMBER = "1"


def _mentions_other_machine(original: str) -> bool:
    for match in _MACHINE_CODE_RE.finditer(original):
        code = match.group(1).lower()
        number = match.group(2)
        if code == _IN_SCOPE_MACHINE_CODE and number == _IN_SCOPE_MACHINE_NUMBER:
            continue
        return True
    return False


def _mentions_in_scope_machine(original: str) -> bool:
    """КДМ-1 явно названа тем же разбором, что и чужая машина (`_MACHINE_CODE_RE`) — используется только для
    смешанного вопроса ниже, не меняет `_mentions_other_machine`."""
    for match in _MACHINE_CODE_RE.finditer(original):
        if match.group(1).lower() == _IN_SCOPE_MACHINE_CODE and match.group(2) == _IN_SCOPE_MACHINE_NUMBER:
            return True
    return False


# Правка F4b, п.1 (H-23, Hidden A): смешанный вопрос «допустимая часть КДМ-1 + чужая машина» сейчас отклонялся
# ЦЕЛИКОМ («Что такое масса 1 м² … листа, который относится к БДМ-2?» → refused), хотя в нём есть допустимая
# часть. Узкая определительная рамка («что такое»/«что означает»/«определение») — короче `_THEORY_FRAME_RE`
# намеренно: полный `_THEORY_FRAME_RE` снял бы отказ и у «Что происходит на КДМ-3?» (регрессия существующего
# теста `test_classify_intent_out_of_scope` — там рамка «что происходит» есть, а машина полностью чужая, без
# допустимой части). Эта рамка — только про запрос ОПРЕДЕЛЕНИЯ/ПОНЯТИЯ, которое само по себе не завязано на
# конкретную машину (масса 1 м², влажность, термин…), а не про любое рассуждение о чужом оборудовании.
_DEFINITIONAL_FRAME_RE = re.compile(r"что\s+так[ао]е|что\s+означа\w*|определени\w*", re.IGNORECASE)
# обобщающее слово «машина» само по себе — не содержательный предмет (ниже), а часть обращения к чужому
# оборудованию («Что такое машина КДМ-3?»)
_GENERIC_MACHINE_WORD_RE = re.compile(r"\bмашин\w*\b", re.IGNORECASE)


def _strip_other_machine_codes(original: str) -> str:
    """Коды ЧУЖИХ машин (`код-ДМ/ПМ + номер`) заменяются пробелом; КДМ-1 не трогается. Правка контроллера,
    раунд 1 (Critical, обход отказа на настоящем корпусе): цифра номера чужой машины («БДМ-2» → «2») иначе
    совпадала бы с номером узла/бассейна КДМ-1 через `_digit_node_process_ids` («Что такое КДМ-3?» нашло
    DOC-composition-lower через узел №3 — ложный `ready` вместо отказа). Используется и здесь (проверка
    содержательного остатка смешанного вопроса), и в `analyze()` (поиск процессов/терминов/пакета доказательств
    смешанного вопроса — `_search_question`, не меняет `parsed`, который видят `classify_intent`/`requires_
    clarification`)."""
    def _blank_other(match: "re.Match[str]") -> str:
        code, number = match.group(1).lower(), match.group(2)
        if code == _IN_SCOPE_MACHINE_CODE and number == _IN_SCOPE_MACHINE_NUMBER:
            return match.group(0)
        return " "
    return _MACHINE_CODE_RE.sub(_blank_other, original)


def _has_substantive_remainder_after_other_machine(original: str) -> bool:
    """Содержательный предмет (слово/термин) остаётся в вопросе после удаления: кода чужой машины
    (`_strip_other_machine_codes`), обобщающего слова «машина»/«машины» (`_GENERIC_MACHINE_WORD_RE`) и самой
    определительной рамки (`_DEFINITIONAL_FRAME_RE` — рамка не считается предметом) — используется
    `_mixed_machine_question_is_admissible`, чтобы «Что такое КДМ-3?»/«Определение КДМ-3?»/«Что означает
    КДМ-3?» (рамка есть, но весь остальной вопрос — только чужая машина) не проходили как допустимые: после
    удаления всего перечисленного не остаётся ни одного слова (`_content_tokens` уже отсекает служебные слова
    русского языка, `_STOPWORDS`, и однобуквенные токены) — только тогда допустимость подтверждена."""
    stripped = _strip_other_machine_codes(original)
    stripped = _GENERIC_MACHINE_WORD_RE.sub(" ", stripped)
    stripped = _DEFINITIONAL_FRAME_RE.sub(" ", stripped)
    return bool(_content_tokens(stripped))


def _mixed_machine_question_is_admissible(original: str) -> bool:
    """Смешанный вопрос про чужую машину допустим ЧАСТИЧНО (H-23): определительная рамка (`_DEFINITIONAL_
    FRAME_RE`) ИЛИ явное упоминание КДМ-1 в том же тексте — И (правка контроллера, раунд 1, Critical) после
    удаления упоминаний чужой машины/рамки в вопросе остаётся содержательный предмет (`_has_substantive_
    remainder_after_other_machine`) — тогда `classify_intent` не отказывает целиком, а продолжает обычную
    классификацию допустимой части; пакет доказательств и так ограничен областью КДМ-1 (`retrieval.search`/
    `process_ids`, `build_evidence_pack`, а поиск самих `process_ids`/терминов для смешанного вопроса идёт по
    тексту БЕЗ кода чужой машины — `analyze()`/`_search_question`), пометку об исключённой (чужой) части
    вопроса ставит `service.py` (F4a, не этот модуль). Чистый вопрос о чужой машине без допустимого остатка
    («Загрузи БДМ-2 из той же книги», «Оптимизируй … КДМ-3», «Что такое КДМ-3?» — рамка есть, но предмет
    вопроса — сама чужая машина, а не что-то третье) — по-прежнему `out_of_scope` целиком."""
    if not (_DEFINITIONAL_FRAME_RE.search(original) or _mentions_in_scope_machine(original)):
        return False
    return _has_substantive_remainder_after_other_machine(original)


def _search_question(parsed: NormalizedQuestion) -> NormalizedQuestion:
    """Правка контроллера, раунд 1 (Critical): для `analyze()` — та же `NormalizedQuestion`, но без кодов
    чужих машин (`_strip_other_machine_codes`) в `.original`/`.normalized`, ТОЛЬКО для поиска процессов/узлов/
    терминов и пакета доказательств (`_candidate_process_ids`/`_resolve_question_terms`/`build_evidence_pack`)
    — не для классификации интента (`classify_intent`) и не для `requires_clarification` (та использует
    исходный `parsed` без изменений: код чужой машины не совпадает ни с одним из её стеблей/единиц/периода).
    Вопрос без упоминания чужой машины — `_strip_other_machine_codes` ничего не находит, возвращается тот же
    `parsed` без изменений (дешёвая проверка `_mentions_other_machine` раньше самой замены)."""
    if not _mentions_other_machine(parsed.original):
        return parsed
    scrubbed = _strip_other_machine_codes(parsed.original)
    return NormalizedQuestion(original=scrubbed, normalized=terms.normalize_ru(scrubbed),
                              unit_hint=parsed.unit_hint, process_hint=parsed.process_hint)


# Правка, раунд 2, п.1 (координатор): сопоставление со стеблями — по НАЧАЛУ токена нормализованного текста,
# не по подстроке всего текста. Старое `stem in text` ловило стебель где угодно внутри слова — «дат» (стебель
# `_PERIOD_STEMS` для «дата») совпадал внутри «подат[ь]» (стемминг «подать»), период ложно считался данным.
# `token.startswith(stem)` для однословных стеблей; стебли с пробелом (фразы вида «по масс») — по-прежнему
# подстрокой во всём тексте (это не одно слово, токенная проверка для них не применима).
def _stem_matches(normalized_text: str, stems: tuple[str, ...]) -> bool:
    tokens = normalized_text.split()
    for stem in stems:
        if " " in stem:
            if stem in normalized_text:
                return True
        elif any(token.startswith(stem) for token in tokens):
            return True
    return False


