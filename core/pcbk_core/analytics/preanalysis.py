    "одиннадцати", "двенадцати", "тринадцати", "четырнадцати", "пятнадцати", "шестнадцати", "семнадцати",
    "восемнадцати", "девятнадцати", "пятидесяти", "шестидесяти", "семидесяти", "восьмидесяти", "сорока",
