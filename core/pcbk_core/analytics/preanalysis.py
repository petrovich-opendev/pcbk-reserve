def _explicit_card_ids(handle: "CorpusHandle", original: str) -> tuple[tuple[str, str], ...]:
    """`(kind, id)` для каждого явно названного в ИСХОДНОМ тексте вопроса токена, который точно существует как
    карточка/механизм корпуса (`retrieval.exact_id_lookup` — точный поиск, не нечёткий: технолог, который помнит
    или скопировал id, получает ровно её, а не растворяется среди результатов `retrieval.search`, п.4 правки
    F1). Без повторов по `id`, в порядке первого упоминания в тексте."""
    seen_ids: set[str] = set()
    result: list[tuple[str, str]] = []
    for match in _EXPLICIT_ID_RE.finditer(original):
        token = match.group(0)
        if token in seen_ids:
            continue
        for kind in ("claim", "mechanism"):
            if retrieval.exact_id_lookup(handle, kind, token) is not None:
                seen_ids.add(token)
                result.append((kind, token))
                break
    return tuple(result)


def build_evidence_pack(handle: "CorpusHandle", process_ids: tuple[str, ...],
                        parsed: NormalizedQuestion) -> tuple[EvidenceCard, ...]:
    """Пункты 7–8 мастер-промпта §7: поиск только доступных источников КДМ-1 и связанной общей теории
    (`retrieval.search` с `process_ids`), отделение наблюдения документа от теории/телеметрии/расчёта/гипотезы
    по `EvidenceCard.kind`/`risk_level`, сборка неизменяемого ограниченного пакета — ровно те карточки, чей
    `id` попадёт в `Preanalysis.allowed_claim_ids`/`allowed_mechanism_ids` (LLM не может выбрать то, чего нет в
    этом пакете — `validator.py` сверяет именно по нему, не по всему корпусу). `retrieval.search` уже
    ограничивает виды (`claim`/`mechanism`) и область (`process_ids`, если известна) — здесь дополнительно не
    открываются ни `fragments` карантина (у них нет записи в `kb_search`, см. `retrieval.py`), ни чужая машина.

    Правка F1, п.4: явно названный id карточки/механизма (`_explicit_card_ids`, точный поиск) идёт ПЕРВЫМ в
    пакете, раньше результатов нечёткого `retrieval.search` — технолог, назвавший id буквально, не должен
    получить её десятой среди похожих по тексту, а должен получить именно её первой."""
    corpus_version = knowledge.corpus_version(handle)
    cards: list[EvidenceCard] = []
    seen: set[str] = set()
    for kind, card_id in _explicit_card_ids(handle, parsed.original):
        if card_id in seen:
            continue
        row_kind = "claims" if kind == "claim" else "mechanisms"
        row = knowledge.get_row(handle, row_kind, card_id)
        if row is None:
            continue
        card = _build_card(handle, kind, row, corpus_version)
        if card is not None:
            seen.add(card_id)
            cards.append(card)
            if len(cards) >= _PACK_MAX_CARDS:
                return tuple(cards)

    query = parsed.normalized or parsed.original
    if not query.strip():
        return tuple(cards)
    hits = retrieval.search(handle, query, kinds=("claim", "mechanism"), limit=_PACK_SEARCH_LIMIT,
                            process_ids=process_ids)
    for hit in hits:
        if hit.id in seen:
            continue
        seen.add(hit.id)
        row_kind = "claims" if hit.kind == "claim" else "mechanisms"
        row = knowledge.get_row(handle, row_kind, hit.id)
        if row is None:
            continue
        card = _build_card(handle, hit.kind, row, corpus_version)
        if card is not None:
            cards.append(card)
        if len(cards) >= _PACK_MAX_CARDS:
            break
    return tuple(cards)


def analyze(identity: "RequestIdentity", request: "AnalysisRequest", handle: "CorpusHandle",
           corpus_version: str) -> tuple[Preanalysis, tuple[EvidenceCard, ...]]:
    """Точка входа `service.py` (Task 4): весь преданализ одним вызовом — `(Preanalysis, пакет доказательств)`.
    `Preanalysis.decision`:
    - `refused` — `classify_intent` вернула `control` или `out_of_scope` (п.6: запрет управляющего пути; явная
      чужая машина) — ни термины, ни процессы, ни пакет доказательств не собираются, `identity` здесь
      используется только по контракту сигнатуры (личность/права уже проверены слоем API до преданализа,
      мастер-промпт §9 пакета: «проверки перед рассуждением» идут до вызова этого модуля);
    - `needs_clarification` — `requires_clarification` вернула `True` (пакет доказательств пуст — уточнение не
      требует чтения данных, мастер-промпт §9 пакета: «до оплачиваемого вызова и чтения данных»);
    - `ready`/`limited_answer` — иначе, с собранным пакетом; различие — пуст пакет или не пуст (нет совпавших
      доказательств в разрешённой области — безопасный ограниченный ответ, не отказ и не выдумка).
    Не обращается к LLM, историану и не публикует ответ — это `service.py`/`llm_adapter.py`/`store.py`.
    `evidence_pack_id` всегда `None` здесь: этот модуль не пишет в `store.py` (не входит в список вызываемых
    модулей по `docs/kdm1/INTERFACES.md`) — `service.py` заполняет реальный id после `store.save_evidence_pack`."""
    del identity  # личность и права уже проверены до преданализа (см. докстринг выше) — не читается здесь
    parsed = original_and_normalized(request)
    intent = classify_intent(parsed)

    if intent == "out_of_scope":
        preanalysis = Preanalysis(
            scope="KDM1_PCBK", intent=intent, decision="refused", resolved_terms=[], process_ids=[],
            conflict_ids=[], missing_fields=[], risk="reference", corpus_version=corpus_version,
            evidence_pack_id=None, allowed_claim_ids=[], allowed_mechanism_ids=[],
            data_access_ready=False, llm_export_policy="public_only",
        )
        return preanalysis, ()

    if intent == "control":
        # Правка, раунд 4 (контроллер): отказ от команды с сохранением допустимой справки (§7 п.6, открытый
        # сценарий T-10). Управляющая часть не выполняется и не передаётся модели (`llm_export_policy="none"`,
        # `service.py` для `intent == "control"` LLM не вызывает), уточнение не запрашивается (оно нужно для
        # действия, которого не будет); справочный пакет собирается как обычно и проходит ту же проверку при
        # выдаче. Чтение данных историана — нет (`data_access_ready=False`).
        # Правка контроллера, раунд 1 (Critical): поиск процессов/терминов/пакета — по тексту без кода чужой
        # машины (`_search_question`), если она упомянута (команда про КДМ-1 рядом с чужой машиной — тот же
        # риск коллизии цифры номера с узлом КДМ-1, что и у смешанного справочного вопроса ниже).
        search_parsed = _search_question(parsed)
        process_ids = _candidate_process_ids(handle, search_parsed)
        resolved_terms = _resolve_question_terms(handle, search_parsed)
        conflict_ids = _collect_conflict_ids(handle, process_ids)
        # в справку к отказу от команды — только неоперационные карточки, чей собственный текст не читается
        # как указание к действию: отказ не должен превращаться в подсказку, как действие выполнить (T-36)
        pack = tuple(card for card in build_evidence_pack(handle, process_ids, search_parsed)
                     if card.risk_level in _CONTROL_SAFE_RISK_LEVELS and not _is_control_command(card.text))
        preanalysis = Preanalysis(
            scope="KDM1_PCBK", intent=intent, decision="limited_answer", resolved_terms=list(resolved_terms),
            process_ids=list(process_ids), conflict_ids=list(conflict_ids), missing_fields=[], risk="control",
            corpus_version=corpus_version, evidence_pack_id=None,
            allowed_claim_ids=[card.id for card in pack if card.kind == "claim"],
            allowed_mechanism_ids=[card.id for card in pack if card.kind == "mechanism"],
            data_access_ready=False, llm_export_policy="none",
        )
        return preanalysis, pack

    # Правка контроллера, раунд 1 (Critical): поиск процессов/узлов/терминов — по тексту без кода чужой машины
    # (`_search_question`; без неё — та же, что и раньше, `parsed`), не по исходному `parsed.original` целиком:
    # номер чужой машины («БДМ-2» → «2») иначе совпадает с номером узла/бассейна КДМ-1 через `_digit_node_
    # process_ids` (воспроизведено на настоящем корпусе). `requires_clarification` ниже — по исходному `parsed`
    # (единицы/период/база не завязаны на код машины).
    search_parsed = _search_question(parsed)
    process_ids = _candidate_process_ids(handle, search_parsed)
    resolved_terms = _resolve_question_terms(handle, search_parsed)
    conflict_ids = _collect_conflict_ids(handle, process_ids)
    # Правка F4b, п.3 (H-29): `period_given` — явный `context.period` клиента (`PeriodWindow` с датами), не
    # угадывание из текста; `mode` — режим диалога самого запроса (`request.mode`), не намерение по тексту.
    period_given = request.context is not None and request.context.period is not None
    # Правка контроллера, раунд 2 (Д17): подпись оборудования — по исходному `parsed` (как единицы/период/
    # база ниже), не по `search_parsed` без кода чужой машины — та же причина, по которой requires_clarification
    # уже вызывается с исходным `parsed`, см. комментарий выше.
    has_equipment_label = _mentions_equipment_link_label(handle, parsed.original)
    # Правка контроллера, раунд 1 (Task 5, п.1 — сужение п.6): перечисление снимает "process" только когда
    # множественность пришла ИЗ ФРАЗЫ узла и номер не дал ни одного кандидата — `search_parsed`, та же
    # область поиска, что у `_candidate_process_ids`/`resolved_terms` выше.
    is_enumeration = (_is_enumeration_question(parsed.original)
                      and _process_ambiguity_is_phrase_only(handle, search_parsed))
    # Правка контроллера, раунд 2 (Task 5, Critical ревью дельты): множество id терминов с ровно одним
    # кандидатом, которые действительно являются базочувствительной величиной (см. докстринг `requires_
    # clarification`, п.5) — вычисляется здесь (только у `analyze()` есть `handle`) и передаётся готовым.
    basis_sensitive_single_candidate_term_ids = frozenset(
        t.candidate_ids[0] for t in resolved_terms
        if t.requires_confirmation and len(t.candidate_ids) == 1
        and _term_is_basis_sensitive_quantity(handle, t.candidate_ids[0])
    )
    needs_clarification, missing_fields = requires_clarification(
        parsed, resolved_terms, process_ids, mode=request.mode, period_given=period_given,
        has_equipment_label=has_equipment_label, is_enumeration=is_enumeration,
        basis_sensitive_single_candidate_term_ids=basis_sensitive_single_candidate_term_ids)

    if needs_clarification:
        preanalysis = Preanalysis(
            scope="KDM1_PCBK", intent=intent, decision="needs_clarification",
            resolved_terms=list(resolved_terms), process_ids=list(process_ids),
            conflict_ids=list(conflict_ids), missing_fields=list(missing_fields), risk=_risk_for(intent),
            corpus_version=corpus_version, evidence_pack_id=None, allowed_claim_ids=[],
            allowed_mechanism_ids=[], data_access_ready=False, llm_export_policy="public_only",
        )
        return preanalysis, ()

    # Правка контроллера, раунд 1 (Task 5, п.7): вопрос ТОЛЬКО о подписи оборудования — полнотекстовый поиск
    # пакета доказательств не вызывается вовсе (даёт только шум), пакет остаётся пустым; `decision` ниже
    # сама становится `limited_answer` (пакет пуст), значение историана технолог получит отдельным
    # механизмом (Task 1), не через карточки. По исходному `parsed` (как `has_equipment_label` выше) — не по
    # `search_parsed` без кода чужой машины, подписи оборудования машинными кодами не являются.
    if _is_equipment_label_only_question(handle, parsed.original):
        pack: tuple[EvidenceCard, ...] = ()
    else:
        pack = build_evidence_pack(handle, process_ids, search_parsed)
    allowed_claim_ids = tuple(card.id for card in pack if card.kind == "claim")
    allowed_mechanism_ids = tuple(card.id for card in pack if card.kind == "mechanism")
    risk = "local_claim" if any(card.critical_local_fact for card in pack) else _risk_for(intent)
    decision = "ready" if pack else "limited_answer"
    preanalysis = Preanalysis(
        scope="KDM1_PCBK", intent=intent, decision=decision, resolved_terms=list(resolved_terms),
        process_ids=list(process_ids), conflict_ids=list(conflict_ids), missing_fields=[], risk=risk,
        corpus_version=corpus_version, evidence_pack_id=None, allowed_claim_ids=list(allowed_claim_ids),
        allowed_mechanism_ids=list(allowed_mechanism_ids), data_access_ready=bool(pack),
        llm_export_policy="public_only",
    )
    return preanalysis, pack
